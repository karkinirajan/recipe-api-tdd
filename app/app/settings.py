# Database
# https://docs.djangoproject.com/en/5.2/ref/settings/#databases


def _legacy_database_url():
    """Build a URL from the original DB_HOST/DB_NAME/DB_USER/DB_PASS variables, else use SQLite."""
    host = os.environ.get("DB_HOST")
    if not host:
        return f"sqlite:///{os.path.join(BASE_DIR, 'db.sqlite3')}"
    user = os.environ.get("DB_USER", "")
    password = os.environ.get("DB_PASS", "")
    name = os.environ.get("DB_NAME", "")
    return f"postgres://{quote(user, safe='')}:{quote(password, safe='')}@{host}/{name}"


